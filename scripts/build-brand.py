#!/usr/bin/env python3
"""Rebuild api/_brand.js: the pigeon mark and the three brand faces, inlined.

Why inline: every guest at the door is a first-time visitor, so a browser
cache never helps. Separate font files would cost the same bytes plus extra
round trips over venue wifi, and Google Fonts would also send each guest's IP
address to Google. Subset to what the page can show, the three faces come to
roughly 30KB.

Usage (needs fonttools and brotli: pip install fonttools brotli):

  python3 scripts/build-brand.py \\
    --mark      pigeon-head-mark.webp \\
    --display   baloo-2-latin-800-normal.woff2 \\
    --sans      nunito-latin-400-normal.woff2 \\
    --mono      jetbrains-mono-latin-500-normal.woff2

Take every source file from the PhilaCon Valley design system (Brand Edition
1.2): the mark from its Logos group, the fonts from its fonts/ folder.
"""
import argparse
import base64
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont

# What each face must cover, as CSS unicode-range values. The browser uses a
# face only for the characters inside its range and falls back to the system
# font for anything else, so a name outside the range still renders.
LATIN = 'U+0020-007E, U+00A0-00FF, U+2013-2014, U+2018-2019, U+201C-201D, U+2026, U+2192'
RANGES = {
    # Headlines, the name sticker, the button, the Discord link.
    'display': LATIN,
    # Body copy: fixed English sentences.
    'sans': LATIN,
    # The status row only: uppercase words, digits, spaces.
    'mono': 'U+0020, U+0030-0039, U+0041-005A',
}


def codepoints(css_range):
    points = set()
    for part in css_range.split(','):
        part = part.strip().removeprefix('U+')
        lo, _, hi = part.partition('-')
        points.update(range(int(lo, 16), int(hi or lo, 16) + 1))
    return points


def subset_woff2(path, css_range):
    font = TTFont(path)
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['kern', 'liga', 'calt']
    options.name_IDs = []
    options.notdef_outline = True
    sub = subset.Subsetter(options)
    sub.populate(unicodes=codepoints(css_range))
    sub.subset(font)
    out = io.BytesIO()
    font.flavor = 'woff2'
    font.save(out)
    return out.getvalue()


def data_uri(mime, data):
    return f'data:{mime};base64,{base64.b64encode(data).decode()}'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mark', required=True)
    for face in RANGES:
        ap.add_argument(f'--{face}', required=True)
    args = ap.parse_args()

    mark = pathlib.Path(args.mark).read_bytes()
    fonts = {face: subset_woff2(getattr(args, face), RANGES[face]) for face in RANGES}

    lines = [
        '// GENERATED by scripts/build-brand.py. Do not edit by hand.',
        '//',
        "// The PhilaCon Valley pigeon-head mark and the three brand faces, from the",
        "// design system (Brand Identity Guidebook Edition 1.2), inlined so the door",
        '// page needs no second request and sends nothing to a font host. Use the',
        '// mark as is: never redraw or recolor it.',
        '',
        f"module.exports.PIGEON_MARK = '{data_uri('image/webp', mark)}';",
        '',
        '// Each face covers only its unicode-range; see RANGES in the build script.',
        'module.exports.FONTS = {',
    ]
    for face, data in fonts.items():
        lines.append(f"  {face}: {{ range: '{RANGES[face]}', src: '{data_uri('font/woff2', data)}' }},")
    lines += ['};', '']

    out = pathlib.Path(__file__).resolve().parent.parent / 'api' / '_brand.js'
    out.write_text('\n'.join(lines))
    sizes = ', '.join(f'{face} {len(data)} B' for face, data in fonts.items())
    print(f'Wrote {out} ({out.stat().st_size} B). Fonts: {sizes}.')


if __name__ == '__main__':
    main()
